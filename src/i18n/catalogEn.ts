export function translateCatalogText(lang: AppLanguage, text: string): string {
  if (lang !== 'en' || !text) return text;
  const trimmed = text.trim();
  const exact = CATALOG_ZH_TO_EN[trimmed];
  if (exact) return exact;

  // Handle composite "经典 · XXX" template variant labels
  if (trimmed.startsWith('经典 · ')) {
    const rest = trimmed.slice('经典 · '.length);
    return `Classic · ${translateCatalogText(lang, rest)}`;
  }

  // Handle "XX · YY" composite labels
  if (trimmed.includes(' · ')) {
    return trimmed
      .split(' · ')
      .map((part) => translateCatalogText(lang, part))
      .join(' · ');
  }

  // Handle "XX + YY" composite labels
  if (trimmed.includes(' + ')) {
    return trimmed
      .split(' + ')
      .map((part) => translateCatalogText(lang, part))
      .join(' + ');
  }

  return text;
}

export function translateDistrictName(lang: AppLanguage, name: string): string {
  if (lang !== 'en') return name;
  return ZH_TO_EN_DISTRICT[name] ?? name;
}

/**
 * Translates built-in auto-generated entity/project/shot names while leaving
 * user-customized names untouched.
 */
export function translateDefaultEntityName(lang: AppLanguage, name: string): string {
  if (lang !== 'en' || !name) return name;

  // Handle "... 副本" / "... 副本 N"
  const copyNumMatch = name.match(/^(.+?)\s+副本\s+(\d+)$/);
  if (copyNumMatch) {
    return `${translateDefaultEntityName(lang, copyNumMatch[1])} Copy ${copyNumMatch[2]}`;
  }
  if (name.endsWith(' 副本')) {
    return `${translateDefaultEntityName(lang, name.slice(0, -3))} Copy`;
  }

  // Known default project / template names
  if (name === '我的海滨片场 (960m)') return 'My Coastal Backlot (960m)';
  const emptyStudioMatch = name.match(/^空地片场\s+(\d+)$/);
  if (emptyStudioMatch) return `Empty Backlot ${emptyStudioMatch[1]}`;

  // Known auto-generated object names
  const dummyMatch = name.match(/^木偶人\s+(\d+)$/);
  if (dummyMatch) return `Mannequin ${dummyMatch[1]}`;
  const treeMatch = name.match(/^乔木\s+(\d+)$/);
  if (treeMatch) return `Tree ${treeMatch[1]}`;
  const rockMatch = name.match(/^岩石\s+(\d+)$/);
  if (rockMatch) return `Rock ${rockMatch[1]}`;
  const glbMatch = name.match(/^3D 白模\s+(\d+)$/);
  if (glbMatch) return `3D Mesh ${glbMatch[1]}`;

  // If pure catalog label or "Label N"
  const numSuffix = name.match(/^([^\d]+?)\s+(\d+)$/);
  if (numSuffix) {
    const mapped = CATALOG_ZH_TO_EN[numSuffix[1].trim()];
    if (mapped) return `${mapped} ${numSuffix[2]}`;
  }

  const exact = CATALOG_ZH_TO_EN[name];
  if (exact) return exact;

  return name;
}
