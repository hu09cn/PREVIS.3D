function partHalfExtents(shape: InventoryPartShape, size: Vec3): Vec3 {
  switch (shape) {
    case 'cylinder': {
      const r = Math.max(size[0], size[1]);
      return [r, size[2] * 0.5, r];
    }
    case 'cone':
      return [size[0], size[1] * 0.5, size[0]];
    case 'sphere':
    case 'dodecahedron':
      return [size[0], size[1], size[2]];
    case 'torus':
      return [size[0] + size[1], size[0] + size[1], size[1]];
    case 'box':
    case 'ramp':
    default:
      return [size[0] * 0.5, size[1] * 0.5, size[2] * 0.5];
  }
}

function rotatePoint(p: Vec3, rot?: Vec3): Vec3 {
  if (!rot) return p;
  let [x, y, z] = p;
  const [rx, ry, rz] = rot;
  if (rx) {
    const c = Math.cos(rx);
    const s = Math.sin(rx);
    [y, z] = [y * c - z * s, y * s + z * c];
  }
  if (ry) {
    const c = Math.cos(ry);
    const s = Math.sin(ry);
    [x, z] = [x * c + z * s, -x * s + z * c];
  }
  if (rz) {
    const c = Math.cos(rz);
    const s = Math.sin(rz);
    [x, y] = [x * c - y * s, x * s + y * c];
  }
  return [x, y, z];
}

function spec(id: string, label: string, parts: InventoryPart[]): AssetVariantSpec {
  let minX = Infinity;
  let minY = Infinity;
  let minZ = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  let maxZ = -Infinity;

  for (const pt of parts) {
    const [hx, hy, hz] = partHalfExtents(pt.shape, pt.size);
    const [px, py, pz] = pt.pos;
    if (!pt.rot) {
      minX = Math.min(minX, px - hx);
      maxX = Math.max(maxX, px + hx);
      minY = Math.min(minY, py - hy);
      maxY = Math.max(maxY, py + hy);
      minZ = Math.min(minZ, pz - hz);
      maxZ = Math.max(maxZ, pz + hz);
    } else {
      for (const sx of [-hx, hx]) {
        for (const sy of [-hy, hy]) {
          for (const sz of [-hz, hz]) {
            const [rx, ry, rz] = rotatePoint([sx, sy, sz], pt.rot);
            minX = Math.min(minX, px + rx);
            maxX = Math.max(maxX, px + rx);
            minY = Math.min(minY, py + ry);
            maxY = Math.max(maxY, py + ry);
            minZ = Math.min(minZ, pz + rz);
            maxZ = Math.max(maxZ, pz + rz);
          }
        }
      }
    }
  }

  const r = (v: number) => Number(Math.max(0.1, v).toFixed(2));
  return {
    id,
    label,
    widthM: r(maxX - minX),
    heightM: r(maxY - minY),
    depthM: r(maxZ - minZ),
    parts,
  };
}

